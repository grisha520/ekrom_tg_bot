"""Парсер сообщений клиента: текст → CustomerRequest (через LLM).

LLM возвращает строгий JSON, который валидируется в доменные модели.
Если LLM недоступен/вернул мусор — поднимаем понятную ошибку выше.
"""

from __future__ import annotations

import json
import re

from ..llm import LLMProvider, get_llm_provider
from ..models import CustomerRequest, ProductSpec

SYSTEM_PROMPT = """\
Ты — ассистент по подбору встраиваемой бытовой техники в магазине ekrom.ru.
Тебе приходит свободное сообщение клиента со списком желаемой техники.
Твоя задача — разобрать его в строгий JSON по схеме ниже. Не придумывай
характеристики, которых нет в сообщении: незаполненные поля оставляй null.

Схема ответа (верни РОВНО такой JSON-объект):
{
  "segment": "эконом | средний | премиум | null",
  "notes": "строка или null — общий контекст запроса",
  "specs": [
    {
      "appliance": "oven | cooktop | hood | microwave | dishwasher | fridge | unknown",
      "raw_text": "исходная строка позиции из сообщения клиента",
      "brand": "Korting | Bosch | ... | null",  // производитель, если указан
      "model": "OGG 771 CFX | null",            // конкретная модель/артикул, если указан
      "width_mm": 600,            // ширина в мм или null (60 см = 600 мм)
      "color": "нержавейка | белый | чёрный | ... | null",
      "install_type": "полновстраиваемая | встраиваемая | ... | null",
      "fuel_type": "электрическая | газовая | индукционная | null",
      "burners": 3,               // число конфорок или null
      "volume_l": 300,            // объём в литрах или null (холодильник/морозилка/винный шкаф)
      "load_kg": 8,               // загрузка в кг или null (стиральная/сушильная машина)
      "energy_class": "A+++",     // класс энергопотребления или null
      "material": "камень",       // материал или null (мойка/поверхность: нержавейка/камень/керамика/стекло/эмаль)
      "max_price": 30000,         // ценовой потолок в рублях или null ('до 30000')
      "exclude_colors": ["чёрный"], // цвета, которые клиент НЕ хочет ('не чёрную')
      "exclude_fuel": ["газовая"],  // топливо, которое клиент НЕ хочет ('кроме газовых')
      "extra": {"уровень шума": "48", "количество программ": "8"}
      // extra — ЛЮБЫЕ прочие характеристики: "название": "значение" словами клиента
    }
  ]
}

Правила:
- Тип техники определяй по смыслу: "духовка/духовой шкаф" → oven;
  "варочная/панель/конфорки" → cooktop; "вытяжка" → hood;
  "СВЧ/микроволновка/микроволновая" → microwave; "посудомойка" → dishwasher;
  "холодильник" → fridge; иначе → unknown.
- ВАЖНО, не путай: "кухонная плита" (отдельностоящая плита с духовкой) → unknown,
  это НЕ cooktop (cooktop — только встраиваемая варочная панель). "Морозильная
  камера/морозильник" → unknown, это НЕ fridge (fridge — только холодильник).
- Размеры в сантиметрах переводи в миллиметры (60 → 600, 45 → 450).
- ШИРИНУ НЕ ВЫДУМЫВАЙ. width_mm заполняй, ТОЛЬКО если клиент прямо назвал размер
  («на 60», «45 см», «шириной 600»). Число рядом с прибором почти всегда значит
  другое — не переноси его в ширину:
    • количество конфорок: «варка 4х», «на 2 конфорки», «на три комф.» → burners,
      width_mm = null (у «4х» НЕТ значения 450 мм!);
    • количество программ/комплектов/камер → extra;
    • ГЛУБИНА/ВЫСОТА («глубина 31 см», «высотой 45») → extra
      ({"глубина": "310"}), это НЕ ширина.
  Если не уверен, о каком размере речь, — оставь width_mm = null: пустое поле
  расширяет подбор, а придуманная ширина отсекает нужный товар совсем.
- ПРИЗНАКИ НЕ ПЕРЕНОСИ МЕЖДУ ПОЗИЦИЯМИ. Каждый пункт списка разбирай отдельно:
  цвет, размер, тип установки и нагрев из одной строки НЕ приписывай соседней.
  Пример: «варка 4х электрика — духовой — вытяжка полновстраиваемая»: слово
  «полновстраиваемая» относится ТОЛЬКО к вытяжке; у варочной панели install_type
  и width_mm остаются null.
- Если указан производитель (Korting, Bosch, Maunfield, Lex…) — заполни brand.
- Если указана конкретная модель/артикул (например "OGG 771 CFX", "HBF011BR0T") —
  заполни model как написано (латиница/цифры, без бренда). Бренд при этом — в brand.
- ИСКЛЮЧЕНИЯ — отрицание желаемого. Любую формулировку вида "не X", "кроме X",
  "только не X", "без X" разбирай как исключение, НЕ как положительное требование:
    • про цвет ("не белую", "только не чёрный", "кроме бежевых") → добавь цвет в
      exclude_colors, поле color оставь null;
    • про топливо/нагрев ("не газовую", "кроме газовых", "только не индукция") →
      добавь в exclude_fuel ("газовая"/"электрическая"/"индукционная"), fuel_type null.
  Можно перечислять несколько исключений. Положительно указанный цвет/топливо
  ("белую", "газовую") — это color/fuel_type, НЕ исключения.
- БЮДЖЕТ — "до 30000", "не дороже 25 тыс", "бюджет 40000", "максимум 50 т.р." →
  max_price в рублях (числом). "30 тыс"/"30 т.р." = 30000. Если потолок не назван — null.
- ХАРАКТЕРИСТИКИ:
    • объём ("на 300 литров", "объём 250 л") → volume_l (число);
    • загрузка ("на 8 кг", "загрузка 7 кг") → load_kg (число, можно дробное);
    • класс энергопотребления ("класс A+++", "энергокласс А++") → energy_class
      ЛАТИНИЦЕЙ как "A+++"/"A++"/"A+"/"A"/"B";
    • материал ("из камня", "нержавеющая мойка", "керамическая") → material
      ("нержавейка"/"камень"/"керамика"/"стекло"/"эмаль");
    • ЛЮБЫЕ ДРУГИЕ характеристики, не попавшие в поля выше (уровень шума, скорость
      отжима, количество программ, число камер, глубина, мощность, тип управления,
      количество комплектов и т.п.) — клади в extra как "название": "значение"
      словами клиента. Пример: "с отжимом 1200 и тихая до 45 дБ" →
      extra: {"отжим": "1200", "уровень шума": "45"}.
    • ФОРМА/ТИП вытяжки (купольная, наклонная, островная, Т-образная, плоская,
      настенная, полновстраиваемая) — это характеристика: клади в
      extra: {"тип кухонной вытяжки": "<форма>"}. Аналогично тип загрузки стиралки
      ("фронтальная"/"вертикальная") → extra: {"тип загрузки": "<...>"}.
- "средний сегмент / средние цены" → segment="средний".
- Отвечай ТОЛЬКО JSON, без пояснений.
"""


# Ширина названа явно: «450», «45 см», «45см», «(500мм)». Число конфорок («4х»,
# «на 2») под это не подходит — там нет ни единиц, ни самого размера.
#
# Границы ищем по ЦИФРАМ, а не по \b: в «500мм» между «0» и «м» границы слова нет
# (кириллица — тоже словесный символ), и \b500\b не срабатывал — законная ширина
# терялась, а вытяжка на 500 мм подбиралась как попало.
def _mentions_width(text: str, width_mm: int) -> re.Match | None:
    cm = width_mm // 10
    return (
        re.search(rf"(?<!\d){width_mm}(?!\d)", text)
        or re.search(rf"(?<!\d){cm}\s*(?:см|cm)(?!\w)", text)
        or re.search(rf"(?<!\d){cm}(?!\d)(?!\s*(?:конфор|комф|прибор|предмет|шт|программ))",
                     text)
    )


def drop_phantom_width(spec: ProductSpec) -> ProductSpec:
    """Убрать ширину, которой клиент не называл (правит spec на месте).

    Страховка под промптом: модель принимала «варка 4х» за 450 мм, и позиция с
    несуществующим требованием выпадала из подбора целиком — у бренда просто нет
    45-см электрических варочных на 4 конфорки. Пустая ширина расширяет подбор,
    придуманная — отсекает нужный товар.

    Также ловим случай, когда число относится к ГЛУБИНЕ или ВЫСОТЕ («глубина 31
    см» у встраиваемой СВЧ): такой размер уезжает в `extra`, а не в ширину.
    """
    if not spec.width_mm:
        return spec
    text = (spec.raw_text or "").lower()
    hit = _mentions_width(text, spec.width_mm)
    if hit is None:
        spec.width_mm = None
        return spec
    # Размер назван, но это глубина/высота — в ширину он не годится.
    before = text[max(0, hit.start() - 20):hit.start()]
    for word, key in (("глубин", "глубина"), ("высот", "высота")):
        if word in before:
            spec.extra.setdefault(key, str(spec.width_mm))
            spec.width_mm = None
            break
    return spec


# ── Утечка характеристик между позициями ─────────────────────────────────────
# Стемы, по которым видно, что характеристика НАЗВАНА в строке позиции.
_FUEL_STEMS: tuple[str, ...] = ("электр", "газ", "индукц", "комбинир")
_INSTALL_STEMS: tuple[str, ...] = ("встра", "встро", "отдельностоящ", "полновстр")


def _mentions_color(text: str, color: str) -> bool:
    """Назван ли этот цвет (или его синоним) в тексте позиции."""
    from ..matching.selector import _title_colors  # локально: parsing→matching

    return bool(_title_colors(text) & _title_colors(color))


def _mentions_fuel(text: str, fuel: str) -> bool:
    stem = next((s for s in _FUEL_STEMS if s in fuel.lower()), None)
    return bool(stem and stem in text)


def _mentions_install(text: str, install: str) -> bool:
    stem = next((s for s in _INSTALL_STEMS if s in install.lower()), None)
    return bool(stem and stem in text)


def _mentions_burners(text: str, burners: int) -> bool:
    return bool(re.search(rf"\b{burners}\b", text))


def _position_texts(specs: list[ProductSpec], message: str = "") -> list[str]:
    """Строки исходного запроса по позициям (иначе — raw_text от модели).

    `raw_text` модель нередко обрезает («духовой шкаф 450» вместо «духовка 450
    (графит или нерж)»), и тогда утечку не отличить от общего требования. Если
    исходное сообщение делится ровно на столько же пунктов, сверяемся по ним.
    """
    from .rule_parser import _split_items

    if message:
        items = _split_items(message)
        if len(items) == len(specs):
            return [s.lower() for s in items]
    return [(spec.raw_text or "").lower() for spec in specs]


def drop_leaked_attributes(
    specs: list[ProductSpec], message: str = ""
) -> list[ProductSpec]:
    """Убрать характеристики, утёкшие в позицию от СОСЕДНЕЙ (правит на месте).

    В живом запросе «духовка 450 (графит или нерж)» цвет и «электро» из строки про
    варочную модель приписала заодно вытяжке — та поехала бы искаться в графите,
    хотя клиент цвета для неё не называл.

    Сбрасываем только явную утечку: характеристики нет в своей строке, но она
    названа в строке другой позиции. Если её нет нигде конкретно — это общее
    требование из шапки («всё не чёрное»), и его сохраняем.
    """
    if len(specs) < 2:
        return specs
    texts = _position_texts(specs, message)
    checks = (
        ("color", _mentions_color),
        ("fuel_type", _mentions_fuel),
        ("install_type", _mentions_install),
        ("burners", _mentions_burners),
    )
    for i, spec in enumerate(specs):
        for field, mentions in checks:
            value = getattr(spec, field)
            if not value or mentions(texts[i], value):
                continue                       # не задано или названо у себя
            if any(mentions(t, value) for j, t in enumerate(texts) if j != i):
                setattr(spec, field, None)     # названо у соседа — это утечка
    return specs


class RequestParser:
    def __init__(self, llm: LLMProvider | None = None) -> None:
        self._llm = llm or get_llm_provider()

    def parse(self, message: str) -> CustomerRequest:
        raw = self._llm.complete_json(SYSTEM_PROMPT, message)
        try:
            data = json.loads(raw)
        except json.JSONDecodeError as exc:  # pragma: no cover - защитный код
            raise ValueError(f"LLM вернул невалидный JSON: {raw!r}") from exc

        request = CustomerRequest.model_validate(data)
        for spec in request.specs:
            drop_phantom_width(spec)
        drop_leaked_attributes(request.specs, message)
        request.original_message = message
        return request
