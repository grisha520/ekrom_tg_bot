"""Разворот сокращений в запросе клиента до разбора.

Клиенты и мебельщики пишут телеграфно: «п/м 450», «варка 3-х комф.», «вытяжка
полновстр 600», «д/ш графит». LLM такие строки трактует наугад — в живом запросе
«п/м 450» уехало в микроволновку, а иногда разбор возвращал пусто и бот отвечал
«не понял». Поэтому текст сначала приводим к явным словам детерминированно, и уже
развёрнутый отдаём и LLM, и правиловому парсеру.

Правила пишем по границам слов: короткие формы («пм», «вп», «см») внутри других
слов ловиться не должны.
"""

from __future__ import annotations

import re

# (шаблон, замена). Порядок важен: сначала более длинные/специфичные формы.
_RULES: tuple[tuple[str, str], ...] = (
    # ── Типы техники ────────────────────────────────────────────────────────
    (r"\bп[/.\-\s]?м[/.\-\s]?м\b", "посудомоечная машина"),      # пмм, п/м/м
    (r"\bп[/.\-]м\b", "посудомоечная машина"),                   # п/м, п.м, п-м
    (r"\bпмм\b", "посудомоечная машина"),
    (r"\bпосудомойк\w*", "посудомоечная машина"),
    (r"\bд[/.\-]ш\b", "духовой шкаф"),                           # д/ш
    (r"\bдухов(?:ка|ки|ку)\b", "духовой шкаф"),
    (r"\bв[/.\-]п\b", "варочная панель"),                        # в/п
    (r"\bвар(?:ка|ки|ку)\b", "варочная панель"),                 # варка
    (r"\bварочн(?:ая|ую|ой)?\s+поверхност\w*", "варочная панель"),
    (r"\bх[/.\-]?(?:к|д)\b", "холодильник"),                     # х/к, х-д
    (r"\bхолод(?:ос|ильничек)\b", "холодильник"),
    (r"\bстир(?:алка|алку|машина)\b", "стиральная машина"),
    (r"\bстир[/.\-\s]?маш\w*", "стиральная машина"),
    (r"\bсуш(?:илка|ильн\w*\s*маш\w*)\b", "сушильная машина"),
    (r"\bмикроволновк\w*", "микроволновая печь"),
    (r"\bизмельчител(?!ь\s+пищевых)\w*", "измельчитель пищевых отходов"),

    # ── Тип установки ───────────────────────────────────────────────────────
    (r"\bполновстр\w*", "полновстраиваемая"),
    (r"\bп[/.\-]в\b", "полновстраиваемая"),
    (r"\bвстр(?:\.|\b)(?!аив)", "встраиваемая"),                 # «встр.», но не «встраиваемая»
    (r"\bотд[/.\-\s]?ст(?:оящ\w*)?\b", "отдельностоящая"),
    (r"\bо[/.\-]с\b", "отдельностоящая"),

    # ── Характеристики ──────────────────────────────────────────────────────
    (r"(\d)\s*[-–]?\s*х?\s*комф\w*", r"\1 конфорки"),            # «3-х комф.» → «3 конфорки»
    (r"(\d)\s*[-–]?\s*х?\s*конф\.", r"\1 конфорки"),
    # «нержавеющая» уже развёрнута — иначе повторный проход даёт «сталь сталь».
    (r"\bнерж(?!авеющая)\w*", "нержавеющая сталь"),
    (r"\bэлектро\b", "электрическая"),
    (r"\bэл[/.\-]?(?:т|тех|во)?\b", "электрическая"),            # эл., эл-во
    (r"\bинд(?:укц)?\.", "индукционная"),
    (r"\bгаз\.", "газовая"),
)

_COMPILED: tuple[tuple[re.Pattern[str], str], ...] = tuple(
    (re.compile(pat, re.IGNORECASE), repl) for pat, repl in _RULES
)


def expand_abbreviations(text: str) -> str:
    """Развернуть сокращения запроса в явные слова.

    Не меняет смысла и не добавляет требований — только раскрывает записи,
    которые клиент сократил («п/м» → «посудомоечная машина»).
    """
    if not text:
        return text
    out = text
    for pattern, repl in _COMPILED:
        out = pattern.sub(repl, out)
    # схлопываем пробелы, появившиеся после замен
    return re.sub(r"[ \t]{2,}", " ", out)
